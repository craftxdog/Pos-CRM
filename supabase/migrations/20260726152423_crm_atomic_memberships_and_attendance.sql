create or replace function public.crm_registrar_asistencia(
  p_id_cliente_crm bigint,
  p_estado text,
  p_id_horario bigint default null,
  p_notas text default null
)
returns public.crm_asistencias
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_empresa_id bigint := (select private.current_empresa_id());
  v_usuario_id bigint := (select private.current_usuario_id());
  v_cliente public.clientes_crm%rowtype;
  v_asistencia public.crm_asistencias%rowtype;
  v_estado text := lower(trim(coalesce(p_estado, '')));
  v_horario_id bigint;
begin
  if v_empresa_id is null then
    raise exception 'No se pudo identificar la empresa del usuario';
  end if;

  if v_estado not in ('presente', 'tarde', 'ausente', 'salida_registrada') then
    raise exception 'Estado de asistencia no permitido';
  end if;

  select *
  into v_cliente
  from public.clientes_crm c
  where c.id = p_id_cliente_crm
    and c.id_empresa = v_empresa_id
  for update;

  if not found then
    raise exception 'No se encontró el cliente';
  end if;

  v_horario_id := coalesce(p_id_horario, v_cliente.id_horario);

  if v_horario_id is not null and not exists (
    select 1
    from public.crm_horarios h
    where h.id = v_horario_id
      and h.id_empresa = v_empresa_id
      and h.activo = true
  ) then
    raise exception 'El horario no existe o está inactivo';
  end if;

  if p_id_horario is not null and p_id_horario is distinct from v_cliente.id_horario then
    update public.clientes_crm
    set id_horario = p_id_horario
    where id = v_cliente.id;
  end if;

  if v_estado = 'salida_registrada' and not exists (
    select 1
    from public.crm_asistencias a
    where a.id_empresa = v_empresa_id
      and a.id_cliente_crm = v_cliente.id
      and a.fecha = current_date
      and a.hora_entrada is not null
  ) then
    raise exception 'Primero registra la entrada del cliente';
  end if;

  insert into public.crm_asistencias (
    id_empresa,
    id_cliente_crm,
    id_horario,
    fecha,
    hora_entrada,
    hora_salida,
    estado,
    registrado_por,
    notas
  )
  values (
    v_empresa_id,
    v_cliente.id,
    v_horario_id,
    current_date,
    case when v_estado in ('presente', 'tarde') then now() else null end,
    case when v_estado = 'salida_registrada' then now() else null end,
    v_estado,
    v_usuario_id,
    nullif(trim(p_notas), '')
  )
  on conflict (id_empresa, id_cliente_crm, fecha)
  do update set
    id_horario = coalesce(excluded.id_horario, crm_asistencias.id_horario),
    hora_entrada = case
      when excluded.estado in ('presente', 'tarde')
        then coalesce(crm_asistencias.hora_entrada, excluded.hora_entrada)
      when excluded.estado = 'ausente' then null
      else crm_asistencias.hora_entrada
    end,
    hora_salida = case
      when excluded.estado = 'salida_registrada' then now()
      when excluded.estado in ('presente', 'tarde', 'ausente') then null
      else crm_asistencias.hora_salida
    end,
    estado = excluded.estado,
    registrado_por = excluded.registrado_por,
    notas = coalesce(excluded.notas, crm_asistencias.notas)
  returning * into v_asistencia;

  return v_asistencia;
end;
$function$;

revoke all on function public.crm_registrar_asistencia(bigint, text, bigint, text)
from public, anon;
grant execute on function public.crm_registrar_asistencia(bigint, text, bigint, text)
to authenticated;

create or replace view public.crm_clientes_asistencia
with (security_invoker = true)
as
select
  c.id,
  c.public_id,
  c.id_empresa,
  c.codigo,
  c.nombres,
  c.apellidos,
  trim(concat_ws(' ', c.nombres, c.apellidos)) as cliente_nombre,
  c.email,
  c.telefono,
  c.estado as cliente_estado,
  c.id_horario,
  h.nombre as horario_nombre,
  h.hora_entrada as horario_entrada,
  h.hora_salida as horario_salida,
  h.dias_semana as horario_dias_semana,
  h.tolerancia_minutos as horario_tolerancia_minutos,
  a.id as asistencia_id,
  a.fecha as asistencia_fecha,
  a.estado as asistencia_estado,
  a.hora_entrada as asistencia_hora_entrada,
  a.hora_salida as asistencia_hora_salida,
  s.id as suscripcion_id,
  s.estado as suscripcion_estado,
  s.fecha_fin as suscripcion_fecha_fin,
  p.nombre as plan_nombre,
  lower(concat_ws(
    ' ',
    c.codigo,
    c.nombres,
    c.apellidos,
    c.email,
    c.telefono
  )) as busqueda
from public.clientes_crm c
left join public.crm_horarios h
  on h.id = c.id_horario
 and h.id_empresa = c.id_empresa
left join lateral (
  select attendance.*
  from public.crm_asistencias attendance
  where attendance.id_empresa = c.id_empresa
    and attendance.id_cliente_crm = c.id
    and attendance.fecha = current_date
  order by attendance.updated_at desc, attendance.id desc
  limit 1
) a on true
left join lateral (
  select subscription.*
  from public.crm_suscripciones subscription
  where subscription.id_empresa = c.id_empresa
    and subscription.id_cliente_crm = c.id
  order by
    (subscription.estado = 'activa') desc,
    subscription.fecha_fin desc,
    subscription.id desc
  limit 1
) s on true
left join public.crm_planes p
  on p.id = s.id_plan
 and p.id_empresa = s.id_empresa;

revoke all on public.crm_clientes_asistencia from public, anon;
grant select on public.crm_clientes_asistencia to authenticated;

-- The implementation needs elevated rights only because invitation recipients
-- are not staff rows yet. It validates auth.uid + auth email before every write.
create or replace function private.crm_completar_invitacion_impl(
  p_invitacion_id uuid,
  p_nombres text,
  p_apellidos text default null,
  p_telefono text default null,
  p_direccion text default null,
  p_identificador_nacional text default null,
  p_identificador_fiscal text default null,
  p_fecha_nacimiento date default null,
  p_notas text default null
)
returns public.clientes_crm
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_invitacion public.crm_invitaciones%rowtype;
  v_cliente public.clientes_crm%rowtype;
  v_plan public.crm_planes%rowtype;
  v_suscripcion public.crm_suscripciones%rowtype;
  v_auth_id uuid := (select auth.uid());
  v_auth_email text := lower((select auth.jwt() ->> 'email'));
begin
  if v_auth_id is null or nullif(v_auth_email, '') is null then
    raise exception 'Debes abrir la invitación con el correo autenticado';
  end if;
  if nullif(trim(p_nombres), '') is null then
    raise exception 'El nombre es obligatorio';
  end if;

  select *
  into v_invitacion
  from public.crm_invitaciones i
  where i.id = p_invitacion_id
    and i.estado = 'pendiente'
    and i.expires_at > now()
    and lower(i.email) = v_auth_email
  for update;

  if not found then
    raise exception 'La invitación no está disponible o ya venció';
  end if;

  if v_invitacion.id_plan is null then
    raise exception 'La invitación no tiene un plan asignado';
  end if;

  select *
  into v_plan
  from public.crm_planes p
  where p.id = v_invitacion.id_plan
    and p.id_empresa = v_invitacion.id_empresa
    and p.activo = true;

  if not found then
    raise exception 'El plan de la invitación ya no está disponible';
  end if;

  select *
  into v_cliente
  from public.clientes_crm c
  where c.id_empresa = v_invitacion.id_empresa
    and lower(c.email) = v_auth_email
  limit 1
  for update;

  if found then
    if v_cliente.id_auth is not null and v_cliente.id_auth <> v_auth_id then
      raise exception 'El correo ya está vinculado a otro cliente';
    end if;

    update public.clientes_crm
    set
      id_auth = v_auth_id,
      nombres = trim(p_nombres),
      apellidos = nullif(trim(p_apellidos), ''),
      telefono = nullif(trim(p_telefono), ''),
      direccion = nullif(trim(p_direccion), ''),
      identificador_nacional = nullif(trim(p_identificador_nacional), ''),
      identificador_fiscal = nullif(trim(p_identificador_fiscal), ''),
      fecha_nacimiento = p_fecha_nacimiento,
      notas = nullif(trim(p_notas), ''),
      estado = 'activo',
      origen = 'invitacion'
    where id = v_cliente.id
    returning * into v_cliente;
  else
    insert into public.clientes_crm (
      id_empresa,
      id_auth,
      nombres,
      apellidos,
      email,
      telefono,
      direccion,
      identificador_nacional,
      identificador_fiscal,
      fecha_nacimiento,
      estado,
      origen,
      notas
    )
    values (
      v_invitacion.id_empresa,
      v_auth_id,
      trim(p_nombres),
      nullif(trim(p_apellidos), ''),
      v_auth_email,
      nullif(trim(p_telefono), ''),
      nullif(trim(p_direccion), ''),
      nullif(trim(p_identificador_nacional), ''),
      nullif(trim(p_identificador_fiscal), ''),
      p_fecha_nacimiento,
      'activo',
      'invitacion',
      nullif(trim(p_notas), '')
    )
    returning * into v_cliente;
  end if;

  if v_cliente.codigo is null or btrim(v_cliente.codigo) = '' then
    update public.clientes_crm
    set codigo = 'CLI-' || lpad(v_cliente.id::text, 6, '0')
    where id = v_cliente.id
    returning * into v_cliente;
  end if;

  select *
  into v_suscripcion
  from public.crm_suscripciones s
  where s.id_empresa = v_invitacion.id_empresa
    and s.id_cliente_crm = v_cliente.id
    and s.estado in ('activa', 'pausada')
  order by s.created_at desc, s.id desc
  limit 1
  for update;

  if found then
    update public.crm_suscripciones
    set
      id_plan = v_plan.id,
      fecha_inicio = current_date,
      fecha_fin = current_date + (v_plan.duracion_dias - 1),
      precio_pactado = v_plan.precio,
      estado = 'activa'
    where id = v_suscripcion.id
    returning * into v_suscripcion;
  else
    insert into public.crm_suscripciones (
      id_empresa,
      id_cliente_crm,
      id_plan,
      fecha_inicio,
      fecha_fin,
      precio_pactado,
      estado
    )
    values (
      v_invitacion.id_empresa,
      v_cliente.id,
      v_plan.id,
      current_date,
      current_date + (v_plan.duracion_dias - 1),
      v_plan.precio,
      'activa'
    )
    returning * into v_suscripcion;
  end if;

  insert into public.crm_suscripcion_historial (
    id_empresa,
    id_suscripcion,
    accion,
    id_plan_nuevo,
    fecha_inicio_nueva,
    fecha_fin_nueva,
    estado_nuevo,
    detalle
  )
  values (
    v_invitacion.id_empresa,
    v_suscripcion.id,
    'invitacion_aceptada',
    v_plan.id,
    v_suscripcion.fecha_inicio,
    v_suscripcion.fecha_fin,
    v_suscripcion.estado,
    jsonb_build_object('invitacion_id', v_invitacion.id)
  );

  update public.crm_invitaciones
  set
    estado = 'aceptada',
    accepted_at = now(),
    id_cliente_crm = v_cliente.id
  where id = v_invitacion.id;

  return v_cliente;
end;
