create or replace function public.crm_gestionar_suscripcion(
  p_id_suscripcion bigint,
  p_accion text,
  p_id_plan bigint default null,
  p_fecha date default current_date
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_empresa_id bigint := (select private.current_empresa_id());
  v_usuario_id bigint := (select private.current_usuario_id());
  v_suscripcion public.crm_suscripciones%rowtype;
  v_anterior public.crm_suscripciones%rowtype;
  v_plan public.crm_planes%rowtype;
  v_accion text := lower(trim(coalesce(p_accion, '')));
  v_fecha date := coalesce(p_fecha, current_date);
  v_historial_accion text;
begin
  if v_empresa_id is null then
    raise exception 'No se pudo identificar la empresa del usuario';
  end if;

  if v_accion not in ('cambiar_plan', 'renovar', 'pausar', 'reactivar', 'cancelar') then
    raise exception 'Acción de suscripción no permitida';
  end if;

  select *
  into v_suscripcion
  from public.crm_suscripciones s
  where s.id = p_id_suscripcion
    and s.id_empresa = v_empresa_id
  for update;

  if not found then
    raise exception 'No se encontró la suscripción';
  end if;

  v_anterior := v_suscripcion;

  if v_accion = 'cambiar_plan' then
    if p_id_plan is null then
      raise exception 'Selecciona el nuevo plan';
    end if;

    select *
    into v_plan
    from public.crm_planes p
    where p.id = p_id_plan
      and p.id_empresa = v_empresa_id
      and p.activo = true;

    if not found then
      raise exception 'El nuevo plan no existe o está inactivo';
    end if;

    update public.crm_suscripciones
    set
      id_plan = v_plan.id,
      fecha_inicio = v_fecha,
      fecha_fin = v_fecha + (v_plan.duracion_dias - 1),
      precio_pactado = v_plan.precio,
      estado = 'activa'
    where id = v_suscripcion.id
    returning * into v_suscripcion;

    v_historial_accion := 'cambio_plan';
  elsif v_accion = 'renovar' then
    select *
    into v_plan
    from public.crm_planes p
    where p.id = v_suscripcion.id_plan
      and p.id_empresa = v_empresa_id;

    if not found then
      raise exception 'El plan actual ya no existe';
    end if;

    update public.crm_suscripciones
    set
      fecha_fin = case
        when v_suscripcion.fecha_fin >= v_fecha
          then v_suscripcion.fecha_fin + v_plan.duracion_dias
        else v_fecha + (v_plan.duracion_dias - 1)
      end,
      precio_pactado = v_plan.precio,
      estado = 'activa'
    where id = v_suscripcion.id
    returning * into v_suscripcion;

    v_historial_accion := 'renovada';
  elsif v_accion = 'pausar' then
    update public.crm_suscripciones
    set estado = 'pausada'
    where id = v_suscripcion.id
    returning * into v_suscripcion;
    v_historial_accion := 'pausada';
  elsif v_accion = 'reactivar' then
    update public.crm_suscripciones
    set estado = 'activa'
    where id = v_suscripcion.id
    returning * into v_suscripcion;
    v_historial_accion := 'reactivada';
  else
    update public.crm_suscripciones
    set estado = 'cancelada'
    where id = v_suscripcion.id
    returning * into v_suscripcion;
    v_historial_accion := 'cancelada';
  end if;

  insert into public.crm_suscripcion_historial (
    id_empresa,
    id_suscripcion,
    accion,
    id_plan_anterior,
    id_plan_nuevo,
    fecha_inicio_anterior,
    fecha_fin_anterior,
    fecha_inicio_nueva,
    fecha_fin_nueva,
    estado_anterior,
    estado_nuevo,
    registrado_por
  )
  values (
    v_empresa_id,
    v_suscripcion.id,
    v_historial_accion,
    v_anterior.id_plan,
    v_suscripcion.id_plan,
    v_anterior.fecha_inicio,
    v_anterior.fecha_fin,
    v_suscripcion.fecha_inicio,
    v_suscripcion.fecha_fin,
    v_anterior.estado,
    v_suscripcion.estado,
    v_usuario_id
  );

  return jsonb_build_object(
    'suscripcion', to_jsonb(v_suscripcion),
    'accion', v_historial_accion
  );
end;
$function$;

revoke all on function public.crm_gestionar_suscripcion(bigint, text, bigint, date)
from public, anon;
grant execute on function public.crm_gestionar_suscripcion(bigint, text, bigint, date)
to authenticated;

create or replace function public.crm_facturar_suscripcion(
  p_id_suscripcion bigint,
  p_estado text default 'pagado',
  p_metodo_pago text default null,
  p_notas text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_empresa_id bigint := (select private.current_empresa_id());
  v_usuario_id bigint := (select private.current_usuario_id());
  v_suscripcion public.crm_suscripciones%rowtype;
  v_cliente public.clientes_crm%rowtype;
  v_plan public.crm_planes%rowtype;
  v_pago public.crm_pagos%rowtype;
  v_moneda text;
begin
  if v_empresa_id is null then
    raise exception 'No se pudo identificar la empresa del usuario';
  end if;

  if p_estado not in ('pendiente', 'pagado', 'vencido') then
    raise exception 'Estado de factura no permitido';
  end if;

  select *
  into v_suscripcion
  from public.crm_suscripciones s
  where s.id = p_id_suscripcion
    and s.id_empresa = v_empresa_id;

  if not found then
    raise exception 'La suscripción no pertenece a la empresa actual';
  end if;

  select * into v_cliente
  from public.clientes_crm c
  where c.id = v_suscripcion.id_cliente_crm
    and c.id_empresa = v_empresa_id;

  select * into v_plan
  from public.crm_planes p
  where p.id = v_suscripcion.id_plan
    and p.id_empresa = v_empresa_id;

  select coalesce(currency, 'USD')
  into v_moneda
  from public.empresa
  where id = v_empresa_id;

  insert into public.crm_pagos (
    id_empresa,
    id_cliente_crm,
    id_suscripcion,
    monto,
    moneda,
    metodo_pago,
    fecha_pago,
    fecha_vencimiento,
    periodo_inicio,
    periodo_fin,
    estado,
    registrado_por,
    notas
  )
  values (
    v_empresa_id,
    v_cliente.id,
    v_suscripcion.id,
    v_suscripcion.precio_pactado,
    coalesce(v_moneda, 'USD'),
    nullif(trim(p_metodo_pago), ''),
    case when p_estado = 'pagado' then now() else null end,
    v_suscripcion.fecha_fin,
    v_suscripcion.fecha_inicio,
    v_suscripcion.fecha_fin,
    p_estado,
    v_usuario_id,
    nullif(trim(p_notas), '')
  )
  returning * into v_pago;

  update public.crm_pagos
  set referencia = format(
    'FAC-%s-%s-%s',
    v_empresa_id,
    to_char(coalesce(v_pago.fecha_pago, v_pago.created_at), 'YYYY'),
    lpad(v_pago.id::text, 6, '0')
  )
  where id = v_pago.id
  returning * into v_pago;

  return jsonb_build_object(
    'cliente', to_jsonb(v_cliente),
    'plan', to_jsonb(v_plan),
    'suscripcion', to_jsonb(v_suscripcion),
    'pago', to_jsonb(v_pago)
  );
end;
$function$;

revoke all on function public.crm_facturar_suscripcion(bigint, text, text, text)
from public, anon;
grant execute on function public.crm_facturar_suscripcion(bigint, text, text, text)
to authenticated;

