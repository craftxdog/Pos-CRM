create or replace function private.crm_sync_cliente_pos()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  cliente_pos_id bigint;
begin
  if tg_op = 'INSERT' then
    if new.id_cliente_proveedor is null then
      insert into public.clientes_proveedores (
        nombres,
        id_empresa,
        direccion,
        telefono,
        email,
        identificador_nacional,
        identificador_fiscal,
        tipo,
        estado
      ) values (
        trim(concat_ws(' ', new.nombres, new.apellidos)),
        new.id_empresa,
        coalesce(new.direccion, ''),
        coalesce(new.telefono, ''),
        new.email,
        coalesce(new.identificador_nacional, ''),
        coalesce(new.identificador_fiscal, ''),
        'cliente',
        new.estado
      )
      returning id into cliente_pos_id;

      new.id_cliente_proveedor = cliente_pos_id;
    end if;
    return new;
  end if;

  if tg_op = 'UPDATE' and new.id_cliente_proveedor is not null then
    update public.clientes_proveedores
    set nombres = trim(concat_ws(' ', new.nombres, new.apellidos)),
        direccion = coalesce(new.direccion, ''),
        telefono = coalesce(new.telefono, ''),
        email = new.email,
        identificador_nacional = coalesce(new.identificador_nacional, ''),
        identificador_fiscal = coalesce(new.identificador_fiscal, ''),
        estado = new.estado
    where id = new.id_cliente_proveedor
      and id_empresa = new.id_empresa;
  end if;

  return new;
end;
$$;

