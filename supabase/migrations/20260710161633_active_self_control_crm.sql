  limit 1;

  if empresa_id is not null then
    return empresa_id;
  end if;

  if to_regclass('public.asignacion_sucursal') is not null then
    execute $sql$
      select s.id_empresa
      from public.usuarios u
      join public.asignacion_sucursal a on a.id_usuario = u.id
      join public.sucursales s on s.id = a.id_sucursal
      where u.id_auth::text = auth.uid()::text
      limit 1
    $sql$
    into empresa_id;
  end if;

  return empresa_id;
end;
$$;

create or replace function private.is_empresa_admin()
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists (
    select 1
    from public.usuarios u
    join public.roles r on r.id = u.id_rol
    where u.id_auth::text = (select auth.uid()::text)
      and lower(r.nombre) in ('superadmin', 'administrador', 'admin')
  );
$$;

