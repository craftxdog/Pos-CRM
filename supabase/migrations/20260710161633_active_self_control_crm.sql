create or replace function private.replace_write_policy_set(
  target_table regclass,
  old_policy text,
  policy_base text,
  predicate text
)
returns void
language plpgsql
set search_path = ''
as $$
begin
  execute format('drop policy if exists %I on %s', old_policy, target_table);
  execute format('drop policy if exists %I on %s', policy_base || '_insert', target_table);
  execute format('drop policy if exists %I on %s', policy_base || '_update', target_table);
  execute format('drop policy if exists %I on %s', policy_base || '_delete', target_table);

  execute format(
    'create policy %I on %s for insert to authenticated with check (%s)',
    policy_base || '_insert',
    target_table,
    predicate
  );
  execute format(
    'create policy %I on %s for update to authenticated using (%s) with check (%s)',
    policy_base || '_update',
    target_table,
    predicate,
    predicate
  );
  execute format(
    'create policy %I on %s for delete to authenticated using (%s)',
    policy_base || '_delete',
    target_table,
    predicate
  );
end
$$;

