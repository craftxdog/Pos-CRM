CREATE FUNCTION public.detalleventaaumentarstock() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
--declarando valores a insertar
declare _habia numeric;
declare _hay numeric;
declare _maneja_inventarios bool;
declare _stock numeric;
begin
--editamos el stock en almacenes
select maneja_inventarios into _maneja_inventarios from productos where id=old.id_producto;
select stock into _stock from almacenes where id_producto=old.id_producto and id_sucursal=old.id_sucursal;

