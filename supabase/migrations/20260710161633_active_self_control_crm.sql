   update almacenes
   set stock= stock + old.cantidad 
   where id_producto=old.id_producto and id_sucursal=old.id_sucursal;

    --asignar valores a las variables
   select stock  into _hay
   from almacenes where id_producto=old.id_producto and id_sucursal=old.id_sucursal;
   select _hay - old.cantidad into _habia
   from almacenes where id_producto=old.id_producto and id_sucursal=old.id_sucursal;

   --insertamos los datos a la tabla de kardex
   insert into kardex(fecha,motivo,cantidad,id_producto,tipo,estado,total,costo,habia,hay)
   values(now(),'Detalle venta eliminada id: ' || old.id,old.cantidad,old.id_producto,'e','activo',old.cantidad*old.precio_compra,old.precio_compra,_habia,_hay);
  
