create or replace function private.ensure_pos_defaults_for_empresa()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  default_sucursal_id bigint;
  default_caja_id bigint;
begin
  if new.id is null then
    return new;
  end if;

  insert into public.sucursales (nombre, direccion_fiscal, id_empresa, simbolo_moneda)
  select 'Principal', coalesce(new.direccion_fiscal, '-'), new.id, coalesce(new.simbolo_moneda, '$')
  where not exists (
    select 1 from public.sucursales s where s.id_empresa = new.id
  )
  returning id into default_sucursal_id;

  if default_sucursal_id is null then
    select s.id
    into default_sucursal_id
    from public.sucursales s
    where s.id_empresa = new.id
    order by s.id
    limit 1;
  end if;

  insert into public.metodos_pago (id_empresa, nombre, icono, color, delete_update)
  select new.id, seed.nombre, '-', seed.color, seed.delete_update
  from (values
    ('Efectivo', '#16a34a', false),
    ('Tarjeta', '#2563eb', true),
    ('Transferencia', '#7c3aed', true),
    ('Mixto', '#f59e0b', false)
  ) as seed(nombre, color, delete_update)
  where not exists (
    select 1
    from public.metodos_pago mp
    where mp.id_empresa = new.id
      and lower(mp.nombre) = lower(seed.nombre)
  );

  if default_sucursal_id is not null then
    insert into public.caja (id_sucursal, descripcion)
    select default_sucursal_id, 'Caja principal'
    where not exists (
      select 1 from public.caja c where c.id_sucursal = default_sucursal_id
    )
    returning id into default_caja_id;

    if default_caja_id is null then
      select c.id
      into default_caja_id
      from public.caja c
      where c.id_sucursal = default_sucursal_id
      order by c.id
      limit 1;
    end if;

    if default_caja_id is not null then
      insert into public.impresoras (id_caja)
      values (default_caja_id)
      on conflict (id_caja) do nothing;

      if new.id_usuario is not null then
        insert into public.asignacion_sucursal (id_sucursal, id_usuario, id_caja)
        select default_sucursal_id, new.id_usuario, default_caja_id
        where not exists (
          select 1
          from public.asignacion_sucursal a
          where a.id_usuario = new.id_usuario
            and a.id_sucursal = default_sucursal_id
        );
      end if;
    end if;
  end if;

  return new;
end;
$$;

revoke all on function private.ensure_pos_defaults_for_empresa() from public, anon, authenticated;

