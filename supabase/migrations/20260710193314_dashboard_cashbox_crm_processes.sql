create or replace function public.dashboartotalventasconfechas(
  _id_empresa integer,
  _fecha_inicio date default null,
  _fecha_fin date default null
)
returns table(fecha date, total_ventas numeric)
language sql
stable
set search_path = public
as $$
  select v.fecha::date as fecha, coalesce(sum(v.monto_total), 0)::numeric as total_ventas
  from public.ventas v
  where v.id_empresa = _id_empresa
    and (_fecha_inicio is null or v.fecha >= _fecha_inicio)
    and (_fecha_fin is null or v.fecha <= _fecha_fin)
    and coalesce(v.estado, '') <> 'pendiente'
  group by v.fecha::date
  order by v.fecha::date;
$$;

