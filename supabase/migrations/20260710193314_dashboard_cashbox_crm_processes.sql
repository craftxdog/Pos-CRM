create or replace function public.confirmar_venta(
  _id_venta bigint,
  _id_usuario bigint,
  _vuelto numeric,
  _id_tipo_comprobante bigint,
  _serie text,
  _id_sucursal bigint,
  _id_cliente bigint,
  _fecha date,
  _monto_total numeric
)
returns setof public.ventas
language plpgsql
set search_path = public
as $$
begin
  update public.ventas
  set
    fecha = coalesce(_fecha, current_date),
    id_usuario = _id_usuario,
    id_sucursal = _id_sucursal,
    id_cliente = _id_cliente,
    monto_total = coalesce(_monto_total, 0),
    sub_total = coalesce(_monto_total, 0),
    vuelto = coalesce(_vuelto, 0),
    estado = 'confirmada',
    cantidad_productos = (
      select coalesce(sum(dv.cantidad), 0)::bigint
      from public.detalle_venta dv
      where dv.id_venta = _id_venta
    )
  where id = _id_venta;

  update public.detalle_venta
  set estado = 'confirmada'
  where id_venta = _id_venta;

  update public.serializacion_comprobantes
  set correlativo = correlativo + 1
  where id_tipo_comprobante = _id_tipo_comprobante
    and sucursal_id = _id_sucursal
    and serie = _serie;

  return query
  select *
  from public.ventas
  where id = _id_venta;
end;
$$;

