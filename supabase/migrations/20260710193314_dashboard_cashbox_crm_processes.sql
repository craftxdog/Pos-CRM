returns table(nombre_producto text, total_vendido numeric, porcentaje numeric)
language sql
stable
set search_path = public
as $$
  with ventas_producto as (
    select
      coalesce(p.nombre, dv.descripcion, 'Producto') as nombre_producto,
      sum(coalesce(dv.cantidad, 0))::numeric as total_vendido
    from public.detalle_venta dv
    join public.ventas v on v.id = dv.id_venta
    left join public.productos p on p.id = dv.id_producto
    where v.id_empresa = _id_empresa
      and (_fecha_inicio is null or v.fecha >= _fecha_inicio)
      and (_fecha_fin is null or v.fecha <= _fecha_fin)
      and coalesce(v.estado, '') <> 'pendiente'
    group by coalesce(p.nombre, dv.descripcion, 'Producto')
  ),
  total as (
    select nullif(sum(total_vendido), 0) as valor from ventas_producto
  )
  select
    vp.nombre_producto,
    vp.total_vendido,
    round((vp.total_vendido / total.valor) * 100, 2) as porcentaje
  from ventas_producto vp
  cross join total
  where total.valor is not null
  order by vp.total_vendido desc, vp.nombre_producto
  limit 5;
$$;

