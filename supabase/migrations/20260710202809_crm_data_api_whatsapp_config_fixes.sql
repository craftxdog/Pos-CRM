create or replace function private.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Legacy code still asks the REST API for `almacen` and `stock`. The actual
-- imported table is `almacenes`, so expose security-invoker compatibility views.
drop view if exists public.stock;
drop view if exists public.almacen;

create or replace view public.almacen
with (security_invoker = true)
as
select
  a.id,
  a.id_sucursal,
  a.id_producto,
  coalesce(p.nombre, s.nombre, 'Almacen principal') as nombre,
  a.stock,
  a.stock_minimo
from public.almacenes a
left join public.productos p on p.id = a.id_producto
left join public.sucursales s on s.id = a.id_sucursal;

create or replace view public.stock
with (security_invoker = true)
as
select
  a.id,
  a.id as id_almacen,
  a.id_sucursal,
  a.id_producto,
  a.stock,
  a.stock_minimo,
  coalesce(p.nombre, 'Producto') as nombre
from public.almacenes a
left join public.productos p on p.id = a.id_producto;

create table if not exists public.crm_whatsapp_config (
  id bigint generated by default as identity primary key,
  id_empresa integer not null references public.empresa(id) on delete cascade,
  proveedor text not null default 'meta_cloud'
    check (proveedor in ('meta_cloud', 'twilio', 'manual')),
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'conectado', 'pausado', 'error')),
  phone_number_id text,
  business_account_id text,
  display_phone text,
  default_country_code text not null default '1',
  default_language text not null default 'es',
  templates jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  updated_by integer references public.usuarios(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id_empresa)
);

create table if not exists public.crm_whatsapp_plantillas (
  id bigint generated by default as identity primary key,
  id_empresa integer not null references public.empresa(id) on delete cascade,
  tipo text not null
    check (tipo in ('bienvenida', 'cobro', 'factura', 'suscripcion_por_vencer')),
  nombre text not null,
  meta_template_name text,
  idioma text not null default 'es',
  cuerpo text not null,
  variables jsonb not null default '[]'::jsonb,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id_empresa, tipo)
);

create table if not exists public.crm_whatsapp_mensajes (
  id bigint generated by default as identity primary key,
  id_empresa integer not null references public.empresa(id) on delete cascade,
  id_cliente_crm bigint references public.clientes_crm(id) on delete set null,
  id_pago bigint references public.crm_pagos(id) on delete set null,
  id_suscripcion bigint references public.crm_suscripciones(id) on delete set null,
  tipo text not null
    check (tipo in ('bienvenida', 'cobro', 'factura', 'suscripcion_por_vencer', 'manual')),
  canal text not null default 'whatsapp' check (canal = 'whatsapp'),
  destino text not null,
  plantilla text,
  cuerpo text not null,
  variables jsonb not null default '{}'::jsonb,
  estado text not null default 'borrador'
    check (estado in ('borrador', 'pendiente', 'enviado', 'error', 'cancelado')),
  provider_message_id text,
  scheduled_at timestamptz not null default now(),
  sent_at timestamptz,
  error text,
  created_by integer references public.usuarios(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists crm_whatsapp_mensajes_empresa_estado_idx
  on public.crm_whatsapp_mensajes (id_empresa, estado, scheduled_at desc);

create table if not exists public.crm_automatizaciones (
  id bigint generated by default as identity primary key,
  id_empresa integer not null references public.empresa(id) on delete cascade,
  evento text not null
    check (evento in ('cliente_creado', 'pago_vencido', 'factura_emitida', 'suscripcion_por_vencer')),
  canal text not null default 'whatsapp' check (canal in ('whatsapp', 'email')),
  tipo_mensaje text not null
    check (tipo_mensaje in ('bienvenida', 'cobro', 'factura', 'suscripcion_por_vencer')),
  dias_antes integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id_empresa, evento, canal)
);

