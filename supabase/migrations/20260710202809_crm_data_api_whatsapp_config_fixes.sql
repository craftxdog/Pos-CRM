insert into public.modulos (nombre, descripcion, icono, link, etiquetas, "check")
select *
from (
  values
    ('WhatsApp CRM', 'Mensajes de cobro, bienvenida, facturas y vencimientos', 'logos:whatsapp-icon', '/crm/whatsapp', '#crm', true)
) as nuevos(nombre, descripcion, icono, link, etiquetas, "check")
where not exists (select 1 from public.modulos m where m.link = nuevos.link);

insert into public.crm_whatsapp_config (id_empresa, proveedor, estado, default_language)
select e.id, 'meta_cloud', 'pendiente', 'es'
from public.empresa e
where not exists (
  select 1 from public.crm_whatsapp_config c where c.id_empresa = e.id
);

insert into public.crm_whatsapp_plantillas (id_empresa, tipo, nombre, meta_template_name, cuerpo, variables)
select e.id, item.tipo, item.nombre, item.meta_template_name, item.cuerpo, item.variables::jsonb
from public.empresa e
cross join (
  values
    ('bienvenida', 'Bienvenida nuevo cliente', 'asc_bienvenida_cliente', 'Hola {{nombre}}, bienvenido a {{empresa}}. Tu registro ya esta activo. Gracias por confiar en nosotros.', '["nombre","empresa"]'),
    ('cobro', 'Nota de cobro', 'asc_nota_cobro', 'Hola {{nombre}}, tienes un pago pendiente de {{monto}} con vencimiento {{fecha_vencimiento}}. Puedes responder este mensaje para coordinar.', '["nombre","monto","fecha_vencimiento"]'),
    ('factura', 'Factura electronica', 'asc_factura_electronica', 'Hola {{nombre}}, tu factura {{referencia}} por {{monto}} ya esta lista. Gracias por tu pago.', '["nombre","referencia","monto"]'),
    ('suscripcion_por_vencer', 'Suscripcion por vencer', 'asc_suscripcion_por_vencer', 'Hola {{nombre}}, tu suscripcion finaliza el {{fecha_fin}}. Te quedan {{dias_restantes}} dia(s).', '["nombre","fecha_fin","dias_restantes"]')
) as item(tipo, nombre, meta_template_name, cuerpo, variables)
where not exists (
  select 1
  from public.crm_whatsapp_plantillas p
  where p.id_empresa = e.id and p.tipo = item.tipo
);

insert into public.crm_automatizaciones (id_empresa, evento, canal, tipo_mensaje, dias_antes, activo)
select e.id, item.evento, 'whatsapp', item.tipo_mensaje, item.dias_antes, true
from public.empresa e
cross join (
  values
    ('cliente_creado', 'bienvenida', 0),
    ('pago_vencido', 'cobro', 0),
    ('factura_emitida', 'factura', 0),
    ('suscripcion_por_vencer', 'suscripcion_por_vencer', 7)
) as item(evento, tipo_mensaje, dias_antes)
where not exists (
  select 1
  from public.crm_automatizaciones a
  where a.id_empresa = e.id and a.evento = item.evento and a.canal = 'whatsapp'
);
