drop view if exists public.stock;
drop view if exists public.almacen;

create table public.almacen (
  id bigint generated by default as identity primary key,
  id_sucursal bigint not null references public.sucursales(id) on delete cascade,
  nombre text not null,
  created_at timestamp with time zone not null default now(),
  unique (id_sucursal, nombre)
);

insert into public.almacen (id_sucursal, nombre)
select s.id, 'General' from public.sucursales s
on conflict (id_sucursal, nombre) do nothing;

alter table public.almacenes add column if not exists id_almacen bigint;
alter table public.almacenes add column if not exists ubicacion text;
update public.almacenes st
set id_almacen = a.id
from public.almacen a
where a.id_sucursal = st.id_sucursal and a.nombre = 'General'
  and st.id_almacen is null;
alter table public.almacenes alter column id_almacen set not null;
alter table public.almacenes
  add constraint almacenes_id_almacen_fkey foreign key (id_almacen)
  references public.almacen(id) on delete cascade;
create unique index if not exists almacenes_almacen_producto_uidx
  on public.almacenes (id_almacen, id_producto);

create or replace function public.sync_stock_sucursal()
returns trigger language plpgsql security invoker set search_path = public as $$
begin
  select a.id_sucursal into new.id_sucursal from public.almacen a where a.id = new.id_almacen;
  if new.id_sucursal is null then raise exception 'Almacén inválido'; end if;
  return new;
end;
$$;
drop trigger if exists trg_sync_stock_sucursal on public.almacenes;
create trigger trg_sync_stock_sucursal before insert or update of id_almacen
on public.almacenes for each row execute function public.sync_stock_sucursal();

create view public.stock with (security_invoker = true) as
select st.id, st.id_almacen, st.id_sucursal, st.id_producto,
  st.stock, st.stock_minimo, st.ubicacion, p.nombre
from public.almacenes st join public.productos p on p.id = st.id_producto;

alter table public.almacen enable row level security;
drop policy if exists "almacen_company_select" on public.almacen;
create policy "almacen_company_select" on public.almacen for select to authenticated
using (exists (select 1 from public.sucursales s where s.id = id_sucursal
  and s.id_empresa = (select private.current_empresa_id())));
drop policy if exists "almacen_company_write" on public.almacen;
create policy "almacen_company_write" on public.almacen for all to authenticated
using (exists (select 1 from public.sucursales s where s.id = id_sucursal
  and s.id_empresa = (select private.current_empresa_id())))
with check (exists (select 1 from public.sucursales s where s.id = id_sucursal
  and s.id_empresa = (select private.current_empresa_id())));

create or replace function public.incrementarstock(_id bigint, cantidad numeric)
returns void language sql security invoker set search_path = public as $$
  update public.almacenes set stock = coalesce(stock, 0) + cantidad where id = _id;
$$;
create or replace function public.reducirstock(_id bigint, cantidad numeric)
returns void language plpgsql security invoker set search_path = public as $$
begin
  update public.almacenes set stock = coalesce(stock, 0) - cantidad
  where id = _id and coalesce(stock, 0) >= cantidad;
  if not found then raise exception 'Stock insuficiente'; end if;
end;
$$;
grant execute on function public.incrementarstock(bigint, numeric) to authenticated;
grant execute on function public.reducirstock(bigint, numeric) to authenticated;

create table if not exists public.movimientos_stock (
  id bigint generated by default as identity primary key,
  id_empresa bigint not null references public.empresa(id) on delete cascade,
  id_almacen bigint not null references public.almacen(id) on delete restrict,
  id_producto bigint not null references public.productos(id) on delete cascade,
  tipo_movimiento text not null check (tipo_movimiento in ('ingreso', 'salida')),
  cantidad numeric not null check (cantidad > 0),
  fecha timestamp with time zone not null default now(),
  detalle text,
  origen text not null default 'inventario',
  creado_por bigint references public.usuarios(id) on delete set null,
  created_at timestamp with time zone not null default now()
);

create index if not exists movimientos_stock_empresa_producto_idx
  on public.movimientos_stock (id_empresa, id_producto, fecha desc);
alter table public.movimientos_stock enable row level security;
drop policy if exists "movimientos_stock_company_select" on public.movimientos_stock;
create policy "movimientos_stock_company_select" on public.movimientos_stock
for select to authenticated using (id_empresa = (select private.current_empresa_id()));
drop policy if exists "movimientos_stock_company_insert" on public.movimientos_stock;
create policy "movimientos_stock_company_insert" on public.movimientos_stock
for insert to authenticated with check (id_empresa = (select private.current_empresa_id()));

